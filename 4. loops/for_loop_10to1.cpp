

// Problem Statement  - print 1 to 10 numbers but in reverse order 
// so to solve in reverse order that is 10 to 1 we need to start from 10 


#include <iostream>
using namespace std;

int main() {

  for( int i = 10; i >= 1; i--) {
    cout << i << endl;
  }
    
    return 0;
}






