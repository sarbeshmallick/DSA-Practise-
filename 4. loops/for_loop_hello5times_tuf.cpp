
// Problem statement- print hello 5 times using loops 

#include <iostream>
using namespace std;

int main() {
    // Print "Hello" 5 times
    for (int i = 1; i <= 5; i++) {
        cout << "Hello" << endl;
    }
    
    return 0;
}




/*

The syntax is written as: for (initialization; condition; updation)

Initialization (int i = 1): This is where we start. It runs only once at the beginning.
Condition (i <= 5): The computer checks this before every round. If true, the loop continues.
Updation (i++): This happens at the end of every round, usually to update the counter. 

*/